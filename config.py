def load_config(config_path=None):
    config = DEFAULT_CONFIG.copy()
    if config_path:
        p = Path(config_path)
        if p.exists():
            with open(p, "r", encoding="utf-8") as f:
                yaml_cfg = yaml.safe_load(f)
                if yaml_cfg:
                    for k, v in yaml_cfg.items():
                        if k in config and isinstance(v, dict):
                            config[k].update(v)
                        else:
                            config[k] = v
    return config
